#!/usr/bin/env node

/**
 * Sozdil word schedule (күн → w4/w5/w6)
 * Usage:
 *   npm run schedule decode > schedule.json   # current schedule as JSON
 *   npm run schedule encode schedule.json     # validate and write web + mobile
 *
 * One source, two outputs: lib/stableSchedule.ts (SCHEDULE_B64) and mobile/assets/dict/schedule.b64.
 * A frozen schedule means editing targets/blacklist never shifts a scheduled day's word.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const WEB = new URL('lib/stableSchedule.ts', root);
const MOBILE = new URL('mobile/assets/dict/schedule.b64', root);

const [cmd, file] = process.argv.slice(2);

if (cmd === 'decode') {
  const b64 = readFileSync(WEB, 'utf8').match(/SCHEDULE_B64 = '([^']*)'/)[1];
  console.log(JSON.stringify(b64 ? JSON.parse(Buffer.from(b64, 'base64').toString('utf8')) : {}, null, 1));
} else if (cmd === 'encode' && file) {
  const schedule = JSON.parse(readFileSync(file, 'utf8'));
  const valid = Object.fromEntries([4, 5, 6].map(n => [
    n,
    new Set(readFileSync(new URL(`words_${n}.ts`, root), 'utf8').match(/"[^"]+"/g).map(s => s.slice(1, -1))),
  ]));

  // The answer must be typeable: it has to pass the same validation list as any guess.
  const errors = [];
  for (const [day, row] of Object.entries(schedule)) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) errors.push(`${day}: bad date`);
    for (const n of [4, 5, 6]) {
      const w = row[`w${n}`];
      if (typeof w !== 'string' || w.length !== n) errors.push(`${day}: w${n}=${w} is not ${n} letters`);
      else if (!valid[n].has(w)) errors.push(`${day}: ${w} is not in words_${n}.ts`);
    }
  }
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }

  const sorted = Object.fromEntries(Object.entries(schedule).sort(([a], [b]) => a.localeCompare(b)));
  const b64 = Buffer.from(JSON.stringify(sorted), 'utf8').toString('base64');
  writeFileSync(WEB, `// Generated by scripts/schedule.mjs — edit via \`npm run schedule decode/encode\`.\nexport const SCHEDULE_B64 = '${b64}';\n`);
  writeFileSync(MOBILE, b64);
  const days = Object.keys(sorted);
  console.log(`✅ ${days.length} days (${days[0]} — ${days[days.length - 1]}) → lib/stableSchedule.ts, mobile/assets/dict/schedule.b64`);
} else {
  console.error('Usage: npm run schedule decode | npm run schedule encode <schedule.json>');
  process.exit(1);
}
